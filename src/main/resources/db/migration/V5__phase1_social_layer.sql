-- ----------------------------------------------------------------------------
-- 1. APP_USERS (sustituye a user_accounts)
-- ----------------------------------------------------------------------------
CREATE TABLE app_users (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    google_email     VARCHAR(255) NOT NULL UNIQUE,
    google_name      VARCHAR(255) NOT NULL,
    participant_name VARCHAR(50)  NOT NULL UNIQUE,
    is_superadmin    BOOLEAN      NOT NULL DEFAULT FALSE,
    linked_at        TIMESTAMP    NOT NULL DEFAULT now()
);

-- Copy existing users (do NOT force id to avoid sequence sync issues)
INSERT INTO app_users (google_email, google_name, participant_name, linked_at)
SELECT google_email, google_name, participant_name, linked_at
FROM user_accounts;

-- Ensure all admin_participant_name from bet_groups exist in app_users
INSERT INTO app_users (google_email, google_name, participant_name, is_superadmin)
SELECT DISTINCT 
    bg.admin_participant_name || '@auto.generated', 
    bg.admin_participant_name, 
    bg.admin_participant_name, 
    TRUE
FROM bet_groups bg
WHERE NOT EXISTS (
    SELECT 1 FROM app_users u WHERE u.participant_name = bg.admin_participant_name
);

-- Ensure all participant_name from bets exist in app_users
INSERT INTO app_users (google_email, google_name, participant_name, is_superadmin)
SELECT DISTINCT 
    b.participant_name || '@auto.generated', 
    b.participant_name, 
    b.participant_name, 
    FALSE
FROM bets b
WHERE NOT EXISTS (
    SELECT 1 FROM app_users u WHERE u.participant_name = b.participant_name
);

-- ----------------------------------------------------------------------------
-- 2. LEAGUES (sustituye a bet_groups, sin competition_type ni bet_mode)
-- ----------------------------------------------------------------------------
CREATE TABLE leagues (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    join_code     VARCHAR(10)  NOT NULL UNIQUE,
    admin_user_id BIGINT       NOT NULL REFERENCES app_users(id),
    created_at    TIMESTAMP    NOT NULL DEFAULT now()
);

-- Do NOT force id, let the sequence generate it
INSERT INTO leagues (name, join_code, admin_user_id, created_at)
SELECT bg.name, bg.join_code, u.id, bg.created_at
FROM bet_groups bg
JOIN app_users u ON u.participant_name = bg.admin_participant_name;


-- ----------------------------------------------------------------------------
-- 3. MEMBERSHIPS
-- ----------------------------------------------------------------------------
CREATE TABLE memberships (
    user_id    BIGINT      NOT NULL REFERENCES app_users(id),
    league_id  BIGINT      NOT NULL REFERENCES leagues(id),
    role       VARCHAR(20) NOT NULL DEFAULT 'MEMBER',
    joined_at  TIMESTAMP   NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, league_id)
);

-- Todos los que tienen una porra son miembros
INSERT INTO memberships (user_id, league_id, role)
SELECT DISTINCT
    u.id,
    l.id,
    CASE WHEN u.id = l.admin_user_id THEN 'ADMIN' ELSE 'MEMBER' END
FROM bets b
JOIN app_users u ON u.participant_name = b.participant_name
JOIN bet_groups bg ON bg.id = b.group_id
JOIN leagues l ON l.join_code = bg.join_code;

-- Los admins siempre son miembros aunque no tengan porra
INSERT INTO memberships (user_id, league_id, role)
SELECT l.admin_user_id, l.id, 'ADMIN'
FROM leagues l
WHERE NOT EXISTS (
    SELECT 1 FROM memberships m 
    WHERE m.user_id = l.admin_user_id AND m.league_id = l.id
);


-- ----------------------------------------------------------------------------
-- 4. COMPETITIONS (Catálogo físico)
-- ----------------------------------------------------------------------------
CREATE TABLE competitions (
    id          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    external_id VARCHAR(50)  UNIQUE,
    created_at  TIMESTAMP    NOT NULL DEFAULT now()
);

INSERT INTO competitions (name)
SELECT DISTINCT competition_type
FROM bet_groups
WHERE competition_type IS NOT NULL;


-- ----------------------------------------------------------------------------
-- 5. EDITIONS (Reutilización de Ligas)
-- ----------------------------------------------------------------------------
CREATE TABLE editions (
    id             BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    league_id      BIGINT      NOT NULL REFERENCES leagues(id),
    competition_id BIGINT      NOT NULL REFERENCES competitions(id),
    bet_mode       VARCHAR(50) NOT NULL CHECK (bet_mode IN ('FULL_BRACKET', 'KNOCKOUTS_ONLY', 'MATCH_DAY')),
    status         VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at     TIMESTAMP   NOT NULL DEFAULT now()
);

INSERT INTO editions (league_id, competition_id, bet_mode, status)
SELECT
    l.id,
    c.id,
    bg.bet_mode,
    'ACTIVE'
FROM bet_groups bg
JOIN leagues l ON l.join_code = bg.join_code
JOIN competitions c ON c.name = bg.competition_type;


-- ----------------------------------------------------------------------------
-- 6. BETS_V2 (Sustituye a bets y añade columnas de pago directas)
-- ----------------------------------------------------------------------------
CREATE TABLE bets_v2 (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT      NOT NULL REFERENCES app_users(id),
    edition_id        BIGINT      NOT NULL REFERENCES editions(id),
    bet_name          VARCHAR(255) NOT NULL,
    hash              TEXT,
    payment_amount    DECIMAL(8,2),
    payment_status    VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (payment_status IN ('PENDING', 'PAID')),
    payment_marked_by BIGINT      REFERENCES app_users(id),
    created_at        TIMESTAMP   NOT NULL DEFAULT now(),
    UNIQUE (user_id, edition_id)
);

-- Do NOT force id!
INSERT INTO bets_v2 (user_id, edition_id, bet_name, hash, payment_status, created_at)
SELECT
    u.id,
    e.id,
    b.bet_name,
    b.hash,
    CASE WHEN b.paid THEN 'PAID' ELSE 'PENDING' END,
    b.created_at
FROM bets b
JOIN app_users u ON u.participant_name = b.participant_name
JOIN bet_groups bg ON bg.id = b.group_id
JOIN leagues l ON l.join_code = bg.join_code
JOIN editions e ON e.league_id = l.id;
