-- Goleadores de cada competición (TopScorerStore). Antes solo vivían en la memoria del servidor y se
-- pedían al proveedor en cada arranque: los puntos de pichichi de un torneo ya cerrado dependían de que
-- el proveedor lo siguiera sirviendo. La lista guardada es la que puntúa; se sustituye entera al cambiar.

CREATE TABLE top_scorers (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    competition_id bigint NOT NULL,
    position integer NOT NULL,
    name varchar(255) NOT NULL,
    short_name varchar(255) NOT NULL,
    goals integer NOT NULL,
    player_position varchar(255) DEFAULT '' NOT NULL,
    player_id varchar(255) DEFAULT '' NOT NULL,
    team varchar(255) DEFAULT '' NOT NULL,
    image_url varchar(2048) DEFAULT '' NOT NULL,
    CONSTRAINT top_scorers_pkey PRIMARY KEY (id),
    CONSTRAINT top_scorers_competition_position_key UNIQUE (competition_id, position),
    CONSTRAINT top_scorers_competition_id_fkey FOREIGN KEY (competition_id) REFERENCES competitions (id) ON DELETE CASCADE
);
