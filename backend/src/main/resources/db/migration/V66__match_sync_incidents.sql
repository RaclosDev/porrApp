-- Cambios de resultado que la sincronización no aplica sola y revisa el administrador de porrApp:
-- un partido terminado que el proveedor devuelve sin acabar o sin marcador, un marcador final distinto
-- y peleas que desaparecen de la cartelera.
CREATE TABLE match_sync_incidents (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id bigint NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
    kind varchar(20) NOT NULL CHECK (kind IN ('REGRESSION', 'SCORE_CHANGE', 'FIGHT_MISSING')),
    status varchar(20) NOT NULL CHECK (status IN ('BLOCKED', 'PENDING', 'APPLIED', 'DISMISSED')),
    previous_status varchar(30),
    previous_home_score integer,
    previous_away_score integer,
    previous_winner_team_id bigint REFERENCES teams(id) ON DELETE SET NULL,
    received_status varchar(30),
    received_home_score integer,
    received_away_score integer,
    received_winner_team_id bigint REFERENCES teams(id) ON DELETE SET NULL,
    first_seen_at timestamptz NOT NULL,
    last_seen_at timestamptz NOT NULL,
    seen_count integer NOT NULL DEFAULT 1,
    resolved_at timestamptz,
    resolved_by varchar(20)
);
-- Como mucho una incidencia abierta de cada tipo por partido.
CREATE UNIQUE INDEX uq_match_sync_incident_open ON match_sync_incidents(match_id, kind)
    WHERE status IN ('BLOCKED', 'PENDING');
CREATE INDEX idx_match_sync_incidents_match ON match_sync_incidents(match_id, kind, id DESC);
CREATE INDEX idx_match_sync_incidents_recent ON match_sync_incidents(last_seen_at DESC);
