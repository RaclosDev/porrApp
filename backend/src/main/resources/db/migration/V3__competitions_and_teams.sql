-- Competiciones (oficiales y propias de una liga), equipos y clasificación de grupos.

CREATE TABLE competitions (
    id bigint GENERATED ALWAYS AS IDENTITY,
    name varchar(100) NOT NULL,
    external_id varchar(50),
    created_at timestamptz DEFAULT now() NOT NULL,
    format_type varchar(30) DEFAULT 'LEAGUE',
    owner_league_id bigint,
    CONSTRAINT competitions_pkey PRIMARY KEY (id),
    CONSTRAINT competitions_external_id_key UNIQUE (external_id),
    CONSTRAINT competitions_owner_league_id_fkey FOREIGN KEY (owner_league_id) REFERENCES leagues (id)
);

CREATE UNIQUE INDEX uq_competitions_owner_league ON competitions (owner_league_id)
    WHERE owner_league_id IS NOT NULL;

CREATE TABLE teams (
    group_name varchar(50),
    manual_tie_breaker integer DEFAULT 0,
    outright_odds double precision,
    qualify_odds double precision,
    win_odds double precision,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    external_id varchar(255),
    name varchar(255) NOT NULL,
    name_en varchar(255),
    logo_url varchar(500),
    competition_id bigint,
    CONSTRAINT teams_pkey PRIMARY KEY (id),
    CONSTRAINT teams_competition_id_fkey FOREIGN KEY (competition_id) REFERENCES competitions (id)
);

CREATE UNIQUE INDEX uq_teams_catalog_name ON teams (name) WHERE competition_id IS NULL;
CREATE UNIQUE INDEX uq_teams_custom_competition_name ON teams (competition_id, lower(name))
    WHERE competition_id IS NOT NULL;

CREATE TABLE group_standings (
    goal_diff integer,
    goals_for integer,
    group_name varchar(2),
    matches_played integer,
    points integer,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    team_id bigint,
    fair_play_points integer DEFAULT 0,
    "position" integer DEFAULT 0,
    status integer DEFAULT 0,
    CONSTRAINT group_standings_pkey PRIMARY KEY (id),
    CONSTRAINT fkr66xh8od1byi207n2f1xwp4ff FOREIGN KEY (team_id) REFERENCES teams (id)
);

CREATE INDEX idx_group_standings_group_pos ON group_standings (group_name, "position");
CREATE INDEX idx_group_standings_pos_pts ON group_standings
    ("position", points DESC, goal_diff DESC, goals_for DESC, fair_play_points DESC);
