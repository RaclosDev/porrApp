-- Llaves de acceso (WebAuthn, PasskeyService): entrar con Face ID, huella o el PIN del dispositivo
-- sin pasar por Google. Solo se guarda la clave pública; la privada nunca sale del dispositivo.

CREATE TABLE passkeys (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id bigint NOT NULL,
    credential_id bytea NOT NULL,
    -- Identificador aleatorio de la cuenta para el autenticador, igual en todas sus llaves.
    user_handle bytea NOT NULL,
    public_key_cose bytea NOT NULL,
    signature_count bigint DEFAULT 0 NOT NULL,
    name varchar(60) NOT NULL,
    created_at timestamptz DEFAULT now() NOT NULL,
    last_used_at timestamptz,
    CONSTRAINT passkeys_pkey PRIMARY KEY (id),
    CONSTRAINT passkeys_credential_id_key UNIQUE (credential_id),
    CONSTRAINT passkeys_user_id_fkey FOREIGN KEY (user_id) REFERENCES app_users (id) ON DELETE CASCADE
);

CREATE INDEX idx_passkeys_user ON passkeys (user_id);
CREATE INDEX idx_passkeys_user_handle ON passkeys (user_handle);

-- Reto de un registro o un inicio de sesión en curso. Un solo uso; caduca en 5 minutos.
CREATE TABLE passkey_challenges (
    id varchar(64) NOT NULL,
    -- Solo en los registros: la cuenta que añade la llave.
    user_id bigint,
    request_json text NOT NULL,
    expires_at timestamptz NOT NULL,
    CONSTRAINT passkey_challenges_pkey PRIMARY KEY (id),
    CONSTRAINT passkey_challenges_user_id_fkey FOREIGN KEY (user_id) REFERENCES app_users (id) ON DELETE CASCADE
);

CREATE INDEX idx_passkey_challenges_expires ON passkey_challenges (expires_at);
