-- ----------------------------------------------------------------------------
-- 1. PRONOSTICOS_GRUPO (Predicciones de clasificación de la fase de grupos)
-- ----------------------------------------------------------------------------
CREATE TABLE pronosticos_grupo (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bet_id        BIGINT       NOT NULL REFERENCES bets_v2(id) ON DELETE CASCADE,
    group_name    VARCHAR(2)   NOT NULL,
    team_id       BIGINT       NOT NULL REFERENCES teams(id),
    position      INTEGER      NOT NULL CHECK (position IN (1, 2, 3, 4)),
    UNIQUE (bet_id, group_name, team_id),
    UNIQUE (bet_id, group_name, position)
);

-- ----------------------------------------------------------------------------
-- 2. PRONOSTICOS_CUADRO (Predicciones del árbol de eliminatorias)
-- ----------------------------------------------------------------------------
CREATE TABLE pronosticos_cuadro (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bet_id        BIGINT       NOT NULL REFERENCES bets_v2(id) ON DELETE CASCADE,
    phase         VARCHAR(20)  NOT NULL CHECK (phase IN ('R16', 'QF', 'SF', 'FINAL', 'THIRD_PLACE')),
    match_index   INTEGER      NOT NULL,
    home_team_id  BIGINT       REFERENCES teams(id),
    away_team_id  BIGINT       REFERENCES teams(id),
    winner_team_id BIGINT      NOT NULL REFERENCES teams(id),
    UNIQUE (bet_id, phase, match_index)
);

-- ----------------------------------------------------------------------------
-- 3. PRONOSTICOS_EXTRA (Predicciones extra: goleador, campeón)
-- ----------------------------------------------------------------------------
CREATE TABLE pronosticos_extra (
    bet_id              BIGINT       PRIMARY KEY REFERENCES bets_v2(id) ON DELETE CASCADE,
    top_scorer          VARCHAR(255),
    champion_team_id    BIGINT       NOT NULL REFERENCES teams(id),
    third_place_team_id BIGINT       REFERENCES teams(id)
);
