-- Ligas y pertenencia de cada usuario a ellas.

CREATE TABLE leagues (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    name varchar(100) NOT NULL,
    join_code varchar(10) NOT NULL,
    admin_user_id bigint NOT NULL,
    created_at timestamptz DEFAULT now() NOT NULL,
    rules text,
    image_updated_at timestamptz,
    is_public boolean DEFAULT false NOT NULL,
    image_key varchar(32),
    creation_key varchar(64),
    entry_fee boolean DEFAULT false NOT NULL,
    CONSTRAINT leagues_pkey PRIMARY KEY (id),
    CONSTRAINT leagues_join_code_key UNIQUE (join_code),
    CONSTRAINT leagues_admin_user_id_fkey FOREIGN KEY (admin_user_id) REFERENCES app_users (id)
);

CREATE UNIQUE INDEX uq_leagues_admin_creation_key ON leagues (admin_user_id, creation_key)
    WHERE creation_key IS NOT NULL;

CREATE TABLE memberships (
    user_id bigint NOT NULL,
    league_id bigint NOT NULL,
    role varchar(20) DEFAULT 'MEMBER' NOT NULL,
    joined_at timestamptz DEFAULT now() NOT NULL,
    payment_status varchar(20) DEFAULT 'PENDING',
    CONSTRAINT memberships_pkey PRIMARY KEY (user_id, league_id),
    CONSTRAINT memberships_league_id_fkey FOREIGN KEY (league_id) REFERENCES leagues (id),
    CONSTRAINT memberships_user_id_fkey FOREIGN KEY (user_id) REFERENCES app_users (id)
);

CREATE INDEX idx_memberships_league_id ON memberships (league_id);
