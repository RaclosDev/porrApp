-- Fórmula 1 (PoolFormat.GRAND_PRIX): en cada Gran Premio se predice el podio, la pole y la vuelta rápida.
-- Cada Gran Premio es una fila de matches sin equipos (su fecha es la de la clasificación, cuando se
-- cierra) y las predicciones son filas de pronosticos_partido con los pilotos elegidos.

ALTER TABLE editions DROP CONSTRAINT editions_bet_mode_check;
ALTER TABLE editions ADD CONSTRAINT editions_bet_mode_check
    CHECK (pool_format IN ('FULL_BRACKET', 'KNOCKOUTS_ONLY', 'MATCH_DAY', 'SURVIVOR', 'GRAND_PRIX'));

-- Pilotos tal como los da ESPN; la escudería y el dorsal son los de su última carrera.
CREATE TABLE race_drivers (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    external_id varchar(30) NOT NULL,
    name varchar(100) NOT NULL,
    short_name varchar(60),
    country varchar(60),
    flag_url varchar(500),
    team_name varchar(100),
    team_color varchar(6),
    car_number varchar(4),
    updated_at timestamptz DEFAULT now() NOT NULL,
    CONSTRAINT race_drivers_pkey PRIMARY KEY (id),
    CONSTRAINT race_drivers_external_id_key UNIQUE (external_id)
);

-- Datos de cada Gran Premio que no caben en matches: la carrera, el circuito y los resultados.
CREATE TABLE race_weekends (
    match_id bigint NOT NULL,
    race_at timestamptz,
    circuit varchar(150),
    city varchar(100),
    country varchar(100),
    sprint boolean DEFAULT false NOT NULL,
    -- Pilotos inscritos (ids de race_drivers separados por comas), en cuanto ESPN publica la lista.
    entry_list varchar(500),
    pole_driver_id bigint,
    first_driver_id bigint,
    second_driver_id bigint,
    third_driver_id bigint,
    fastest_lap_driver_id bigint,
    results_at timestamptz,
    results_notified_at timestamptz,
    CONSTRAINT race_weekends_pkey PRIMARY KEY (match_id),
    CONSTRAINT race_weekends_match_fkey FOREIGN KEY (match_id) REFERENCES matches (id) ON DELETE CASCADE,
    CONSTRAINT race_weekends_pole_fkey FOREIGN KEY (pole_driver_id) REFERENCES race_drivers (id),
    CONSTRAINT race_weekends_first_fkey FOREIGN KEY (first_driver_id) REFERENCES race_drivers (id),
    CONSTRAINT race_weekends_second_fkey FOREIGN KEY (second_driver_id) REFERENCES race_drivers (id),
    CONSTRAINT race_weekends_third_fkey FOREIGN KEY (third_driver_id) REFERENCES race_drivers (id),
    CONSTRAINT race_weekends_fastest_lap_fkey FOREIGN KEY (fastest_lap_driver_id) REFERENCES race_drivers (id)
);

-- Predicción de un Gran Premio: podio, pole y vuelta rápida.
ALTER TABLE pronosticos_partido
    ADD COLUMN race_first_driver_id bigint,
    ADD COLUMN race_second_driver_id bigint,
    ADD COLUMN race_third_driver_id bigint,
    ADD COLUMN race_pole_driver_id bigint,
    ADD COLUMN race_fastest_lap_driver_id bigint,
    ADD CONSTRAINT pronosticos_partido_race_first_fkey FOREIGN KEY (race_first_driver_id) REFERENCES race_drivers (id),
    ADD CONSTRAINT pronosticos_partido_race_second_fkey FOREIGN KEY (race_second_driver_id) REFERENCES race_drivers (id),
    ADD CONSTRAINT pronosticos_partido_race_third_fkey FOREIGN KEY (race_third_driver_id) REFERENCES race_drivers (id),
    ADD CONSTRAINT pronosticos_partido_race_pole_fkey FOREIGN KEY (race_pole_driver_id) REFERENCES race_drivers (id),
    ADD CONSTRAINT pronosticos_partido_race_fastest_lap_fkey FOREIGN KEY (race_fastest_lap_driver_id) REFERENCES race_drivers (id);

INSERT INTO competitions (name, external_id, format_type)
SELECT 'Fórmula 1', 'f1', 'RACE'
WHERE NOT EXISTS (SELECT 1 FROM competitions WHERE external_id = 'f1');
