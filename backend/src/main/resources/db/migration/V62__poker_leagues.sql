CREATE TABLE poker_sessions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    league_id bigint NOT NULL REFERENCES leagues(id) ON DELETE CASCADE,
    scheduled_on date NOT NULL,
    started_at bigint,
    closed_at bigint,
    revision bigint NOT NULL DEFAULT 0,
    settings jsonb NOT NULL,
    entries jsonb NOT NULL DEFAULT '[]',
    eliminations jsonb NOT NULL DEFAULT '[]',
    blind_clock jsonb
);

CREATE UNIQUE INDEX uq_poker_session_open ON poker_sessions (league_id) WHERE closed_at IS NULL;
CREATE INDEX idx_poker_sessions_history ON poker_sessions (league_id, scheduled_on DESC, id DESC);
