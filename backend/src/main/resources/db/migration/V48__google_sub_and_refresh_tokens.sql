-- ============================================================================
-- V48__google_sub_and_refresh_tokens.sql
--
-- 1. app_users.google_sub: identificador estable de la cuenta de Google (claim
--    "sub" del ID token). El email de una cuenta puede cambiar; el sub no. Las
--    cuentas que ya existen lo reciben al volver a entrar (AuthService).
-- 2. Sesiones con refresh token rotatorio. Cada inicio de sesión abre una
--    familia; cada refresco gasta el token presentado y crea otro en la misma
--    familia. Si vuelve a llegar un token ya gastado, se revoca la familia.
--    Solo se guarda el SHA-256 del token, nunca su valor.
-- ============================================================================

ALTER TABLE app_users ADD COLUMN google_sub VARCHAR(255);
ALTER TABLE app_users ADD CONSTRAINT app_users_google_sub_key UNIQUE (google_sub);

CREATE TABLE refresh_token_families (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- Caducidad absoluta de la sesión: rotar el token no la alarga.
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ
);
CREATE INDEX idx_refresh_token_families_user ON refresh_token_families(user_id);

CREATE TABLE refresh_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_id  BIGINT      NOT NULL REFERENCES refresh_token_families(id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- Cuándo se cambió por el siguiente. Volver a presentarlo es una reutilización.
    rotated_at TIMESTAMPTZ
);
CREATE INDEX idx_refresh_tokens_family ON refresh_tokens(family_id);
