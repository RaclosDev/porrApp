-- Registro con email y contraseña verificado con un código de 6 dígitos (PasswordAuthService).
-- La cuenta solo se crea al escribir el código que llega al email. Una fila por email: pedir otro
-- código la sustituye. Solo se guardan el hash BCrypt de la contraseña y el SHA-256 del código.

CREATE TABLE pending_registrations (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    email varchar(254) NOT NULL,
    password_hash varchar(100) NOT NULL,
    code_hash varchar(64) NOT NULL,
    attempts integer DEFAULT 0 NOT NULL,
    created_at timestamptz DEFAULT now() NOT NULL,
    expires_at timestamptz NOT NULL,
    CONSTRAINT pending_registrations_pkey PRIMARY KEY (id),
    CONSTRAINT pending_registrations_email_key UNIQUE (email)
);

CREATE INDEX idx_pending_registrations_expires ON pending_registrations (expires_at);
