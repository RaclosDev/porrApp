-- Soporte para predicciones partido a partido y por jornadas (Fase 3: 1X2 y marcador)

CREATE TABLE pronosticos_partido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prediction_id BIGINT NOT NULL REFERENCES predictions(id) ON DELETE CASCADE,
    match_id BIGINT NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
    home_score INTEGER,
    away_score INTEGER,
    prediction_sign VARCHAR(5),
    points_awarded INTEGER,
    is_exact_score BOOLEAN,
    is_correct_sign BOOLEAN,
    scoring_details VARCHAR(255),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_prediction_match UNIQUE (prediction_id, match_id)
);

CREATE INDEX idx_pronosticos_partido_prediction ON pronosticos_partido(prediction_id);
CREATE INDEX idx_pronosticos_partido_match ON pronosticos_partido(match_id);
