CREATE TABLE organized_tournaments (
    id bigint PRIMARY KEY REFERENCES leagues(id) ON DELETE CASCADE,
    activity varchar(80) NOT NULL,
    participant_type varchar(20) NOT NULL CHECK (participant_type IN ('INDIVIDUAL', 'TEAM', 'PAIR')),
    format varchar(20) NOT NULL DEFAULT 'MANUAL' CHECK (format IN ('MANUAL', 'LEAGUE', 'KNOCKOUT')),
    public_id uuid NOT NULL UNIQUE,
    published boolean NOT NULL DEFAULT false,
    revision bigint NOT NULL DEFAULT 0,
    win_points integer NOT NULL DEFAULT 3,
    draw_points integer NOT NULL DEFAULT 1,
    loss_points integer NOT NULL DEFAULT 0,
    participants jsonb NOT NULL DEFAULT '[]',
    matches jsonb NOT NULL DEFAULT '[]'
);

CREATE TABLE tournament_result_changes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id bigint NOT NULL REFERENCES organized_tournaments(id) ON DELETE CASCADE,
    revision bigint NOT NULL,
    changed_at timestamptz NOT NULL DEFAULT now(),
    actor_id bigint REFERENCES app_users(id) ON DELETE SET NULL,
    before_result jsonb NOT NULL,
    after_result jsonb NOT NULL
);
CREATE INDEX idx_tournament_changes ON tournament_result_changes(tournament_id, revision);
