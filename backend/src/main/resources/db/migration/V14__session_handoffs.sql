-- Traspaso de sesión de Safari a la app instalada en iPhone (SessionHandoffService). iOS copia las
-- cookies a la app al añadirla a la pantalla de inicio, pero no el resto del almacenamiento.
-- Cada código es de un solo uso y vive 30 minutos; solo se guarda su SHA-256.

CREATE TABLE session_handoffs (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id bigint NOT NULL,
    code_hash varchar(64) NOT NULL,
    created_at timestamptz DEFAULT now() NOT NULL,
    expires_at timestamptz NOT NULL,
    CONSTRAINT session_handoffs_pkey PRIMARY KEY (id),
    CONSTRAINT session_handoffs_code_hash_key UNIQUE (code_hash),
    CONSTRAINT session_handoffs_user_id_fkey FOREIGN KEY (user_id) REFERENCES app_users (id) ON DELETE CASCADE
);

CREATE INDEX idx_session_handoffs_user ON session_handoffs (user_id);
