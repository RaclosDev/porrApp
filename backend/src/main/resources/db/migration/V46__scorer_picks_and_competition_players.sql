-- Pichichi en cualquier competición de fútbol con goleadores.

-- Jugadores que juegan cada competición (plantillas del proveedor): de aquí se elige el pichichi y contra
-- ellos se empareja lo que se escribe a mano. No se borran: un jugador traspasado a media temporada puede
-- seguir siendo el máximo goleador.
CREATE TABLE competition_players (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    competition_id bigint NOT NULL,
    player_id varchar(255) NOT NULL,
    name varchar(255) NOT NULL,
    short_name varchar(255) DEFAULT '' NOT NULL,
    team varchar(255) DEFAULT '' NOT NULL,
    player_position varchar(255) DEFAULT '' NOT NULL,
    fetched_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT competition_players_pkey PRIMARY KEY (id),
    CONSTRAINT competition_players_competition_player_key UNIQUE (competition_id, player_id),
    CONSTRAINT competition_players_competition_id_fkey FOREIGN KEY (competition_id) REFERENCES competitions (id) ON DELETE CASCADE
);

-- Pichichi de una porra. En las ligas sin cuadro (jornadas, eliminatorias sorteadas) es la elección entera;
-- en el cuadro de un torneo con grupos el nombre sigue dentro del cuadro y aquí solo se anota el jugador
-- que le asigna el administrador, que vale mientras el nombre escrito no cambie.
CREATE TABLE scorer_picks (
    prediction_id bigint NOT NULL,
    written_name varchar(120) NOT NULL,
    player_id varchar(255),
    player_name varchar(255),
    resolved_by_admin boolean DEFAULT false NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT scorer_picks_pkey PRIMARY KEY (prediction_id),
    CONSTRAINT scorer_picks_prediction_id_fkey FOREIGN KEY (prediction_id) REFERENCES predictions (id) ON DELETE CASCADE
);
