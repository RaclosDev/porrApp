-- Partidos de cada competición.

CREATE TABLE matches (
    away_score integer,
    finished boolean,
    group_name varchar(50),
    home_score integer,
    away_team_id bigint,
    home_team_id bigint,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    match_date timestamptz,
    external_id varchar(255),
    round varchar(255),
    stadium_id varchar(255),
    display_clock varchar(255),
    winner_team_id bigint,
    competition_id bigint,
    status varchar(30) DEFAULT 'SCHEDULED',
    home_fair_play integer DEFAULT 0,
    away_fair_play integer DEFAULT 0,
    CONSTRAINT matches_pkey PRIMARY KEY (id),
    CONSTRAINT uq_matches_external_id UNIQUE (external_id),
    CONSTRAINT fk2e8erbfecb0tjtq9iudg36bxu FOREIGN KEY (away_team_id) REFERENCES teams (id),
    CONSTRAINT fk8k68nekawp47js52dq8720voe FOREIGN KEY (home_team_id) REFERENCES teams (id),
    CONSTRAINT fk_match_competition FOREIGN KEY (competition_id) REFERENCES competitions (id),
    CONSTRAINT fk_match_winner FOREIGN KEY (winner_team_id) REFERENCES teams (id)
);

CREATE INDEX idx_matches_comp_date ON matches (competition_id, match_date);
CREATE INDEX idx_matches_comp_round_finished ON matches (competition_id, round, finished);
CREATE INDEX idx_matches_competition_id ON matches (competition_id);
CREATE INDEX idx_matches_date ON matches (match_date);
CREATE INDEX idx_matches_group_name ON matches (group_name);
