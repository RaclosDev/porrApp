-- Esquema consolidado de las migraciones V1–V71 originales (en git hasta e619cc2).
-- Usuarios y sesiones con refresh tokens.

CREATE TABLE app_users (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    google_email varchar(255) NOT NULL,
    google_name varchar(255),
    participant_name varchar(50) NOT NULL,
    linked_at timestamptz DEFAULT now() NOT NULL,
    last_selected_group_id bigint,
    avatar_updated_at timestamptz,
    google_sub varchar(255),
    profile_setup_completed boolean DEFAULT false NOT NULL,
    match_reminders_enabled boolean DEFAULT true NOT NULL,
    member_joined_alerts_enabled boolean DEFAULT true NOT NULL,
    avatar_key varchar(32),
    last_active_at timestamptz DEFAULT now() NOT NULL,
    CONSTRAINT app_users_pkey PRIMARY KEY (id),
    CONSTRAINT app_users_google_email_key UNIQUE (google_email),
    CONSTRAINT app_users_google_sub_key UNIQUE (google_sub)
);

CREATE TABLE refresh_token_families (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id bigint NOT NULL,
    created_at timestamptz DEFAULT now() NOT NULL,
    expires_at timestamptz NOT NULL,
    revoked_at timestamptz,
    CONSTRAINT refresh_token_families_pkey PRIMARY KEY (id),
    CONSTRAINT refresh_token_families_user_id_fkey FOREIGN KEY (user_id) REFERENCES app_users (id) ON DELETE CASCADE
);

CREATE INDEX idx_refresh_token_families_user ON refresh_token_families (user_id);

CREATE TABLE refresh_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    family_id bigint NOT NULL,
    token_hash varchar(64) NOT NULL,
    created_at timestamptz DEFAULT now() NOT NULL,
    rotated_at timestamptz,
    CONSTRAINT refresh_tokens_pkey PRIMARY KEY (id),
    CONSTRAINT refresh_tokens_token_hash_key UNIQUE (token_hash),
    CONSTRAINT refresh_tokens_family_id_fkey FOREIGN KEY (family_id) REFERENCES refresh_token_families (id) ON DELETE CASCADE
);

CREATE INDEX idx_refresh_tokens_family ON refresh_tokens (family_id);
