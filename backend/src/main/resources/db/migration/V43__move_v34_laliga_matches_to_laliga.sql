-- V43__move_v34_laliga_matches_to_laliga.sql
--
-- V34 da por hecho que LaLiga es la competición 4, como en producción. En una
-- base nueva la 4 es la Premier League (orden de V21), así que las jornadas 1-10
-- de LaLiga acababan colgando de la Premier. Se mueven a la competición esp.1.
