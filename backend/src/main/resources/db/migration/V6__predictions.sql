-- Predicciones de cada usuario por edición y sus pronósticos partido a partido.
-- Los nombres bets_v2_* de la secuencia y las restricciones (también las NOT NULL, con nombre desde
-- Postgres 18) se conservan para coincidir con producción.

CREATE TABLE predictions (
    id bigint CONSTRAINT bets_v2_id_not_null NOT NULL GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME bets_v2_id_seq),
    user_id bigint CONSTRAINT bets_v2_user_id_not_null NOT NULL,
    edition_id bigint CONSTRAINT bets_v2_edition_id_not_null NOT NULL,
    prediction_name varchar(255) CONSTRAINT bets_v2_bet_name_not_null NOT NULL,
    payment_amount numeric(8, 2),
    payment_status varchar(20) DEFAULT 'PENDING' CONSTRAINT bets_v2_payment_status_not_null NOT NULL,
    payment_marked_by bigint,
    created_at timestamptz DEFAULT now() CONSTRAINT bets_v2_created_at_not_null NOT NULL,
    total_points integer DEFAULT 0,
    r1_points integer DEFAULT 0,
    r32_points integer DEFAULT 0,
    r16_points integer DEFAULT 0,
    qf_points integer DEFAULT 0,
    sf_points integer DEFAULT 0,
    finals_points integer DEFAULT 0,
    scorer_points integer DEFAULT 0,
    match_points integer DEFAULT 0,
    score_calculated_at timestamptz,
    bracket_data text,
    CONSTRAINT bets_v2_pkey PRIMARY KEY (id),
    CONSTRAINT bets_v2_payment_status_check CHECK (payment_status IN ('PENDING', 'PAID')),
    CONSTRAINT uq_predictions_user_edition UNIQUE (user_id, edition_id),
    CONSTRAINT bets_v2_edition_id_fkey FOREIGN KEY (edition_id) REFERENCES editions (id),
    CONSTRAINT bets_v2_payment_marked_by_fkey FOREIGN KEY (payment_marked_by) REFERENCES app_users (id),
    CONSTRAINT bets_v2_user_id_fkey FOREIGN KEY (user_id) REFERENCES app_users (id)
);

CREATE INDEX idx_predictions_edition_payment ON predictions (edition_id, payment_status);
CREATE INDEX idx_predictions_edition_total_pts ON predictions (edition_id, total_points DESC);
CREATE INDEX idx_predictions_user ON predictions (user_id);

CREATE TABLE pronosticos_partido (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    prediction_id bigint NOT NULL,
    match_id bigint NOT NULL,
    home_score integer,
    away_score integer,
    prediction_sign varchar(5),
    points_awarded integer,
    is_exact_score boolean,
    is_correct_sign boolean,
    scoring_details varchar(255),
    created_at timestamptz DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pronosticos_partido_pkey PRIMARY KEY (id),
    CONSTRAINT uq_prediction_match UNIQUE (prediction_id, match_id),
    CONSTRAINT pronosticos_partido_match_id_fkey FOREIGN KEY (match_id) REFERENCES matches (id) ON DELETE CASCADE,
    CONSTRAINT pronosticos_partido_prediction_id_fkey FOREIGN KEY (prediction_id) REFERENCES predictions (id) ON DELETE CASCADE
);

CREATE INDEX idx_pronosticos_partido_match ON pronosticos_partido (match_id);
