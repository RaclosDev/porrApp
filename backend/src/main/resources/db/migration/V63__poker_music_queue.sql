-- Cola de música del modo TV del póker: los jugadores piden canciones y la cabeza de la cola es la que suena.
CREATE TABLE poker_music_queue (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    league_id bigint NOT NULL REFERENCES leagues(id) ON DELETE CASCADE,
    video_id varchar(11) NOT NULL,
    title varchar(150) NOT NULL,
    channel varchar(100) NOT NULL DEFAULT '',
    added_by bigint NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    added_by_name varchar(60) NOT NULL,
    created_at bigint NOT NULL
);

CREATE INDEX idx_poker_music_queue_league ON poker_music_queue (league_id, id);
