ALTER TABLE matches ADD COLUMN IF NOT EXISTS status VARCHAR(30) DEFAULT 'SCHEDULED';

CREATE TABLE sync_audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider VARCHAR(50) NOT NULL,
    competition_id BIGINT REFERENCES competitions(id) ON DELETE SET NULL,
    status VARCHAR(20) NOT NULL,
    matches_updated INTEGER NOT NULL DEFAULT 0,
    teams_updated INTEGER NOT NULL DEFAULT 0,
    duration_ms BIGINT NOT NULL DEFAULT 0,
    error_message TEXT,
    synced_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_sync_audit_provider ON sync_audit_logs(provider);
CREATE INDEX idx_sync_audit_synced_at ON sync_audit_logs(synced_at DESC);
