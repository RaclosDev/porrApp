-- Ediciones (una competición jugada dentro de una liga) y reglas de puntuación.

CREATE TABLE editions (
    id bigint GENERATED ALWAYS AS IDENTITY,
    league_id bigint NOT NULL,
    competition_id bigint NOT NULL,
    pool_format varchar(50) NOT NULL,
    status varchar(20) DEFAULT 'ACTIVE' NOT NULL,
    created_at timestamptz DEFAULT now() NOT NULL,
    pichichi boolean DEFAULT true NOT NULL,
    lock_date timestamptz,
    scoring_rules_json text,
    lock_mode varchar(20) DEFAULT 'FIXED_DATE' NOT NULL,
    lock_offset_minutes integer DEFAULT 0 NOT NULL,
    CONSTRAINT editions_pkey PRIMARY KEY (id),
    CONSTRAINT editions_bet_mode_check CHECK (pool_format IN ('FULL_BRACKET', 'KNOCKOUTS_ONLY', 'MATCH_DAY')),
    CONSTRAINT editions_competition_id_fkey FOREIGN KEY (competition_id) REFERENCES competitions (id),
    CONSTRAINT editions_league_id_fkey FOREIGN KEY (league_id) REFERENCES leagues (id)
);

CREATE INDEX idx_editions_league_status ON editions (league_id, status);

CREATE TABLE scoring_rule_sets (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    name varchar(100) NOT NULL,
    rules_json text NOT NULL,
    version integer DEFAULT 1 NOT NULL,
    created_at timestamptz DEFAULT now() NOT NULL,
    CONSTRAINT scoring_rule_sets_pkey PRIMARY KEY (id)
);
